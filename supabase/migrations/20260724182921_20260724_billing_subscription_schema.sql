/*
# Health Cloud Billing & Subscription Schema

## Summary
Adds complete billing infrastructure: subscriptions, payments, invoices, grace period config, and subscription event audit trail.

## New Tables
1. `tenant_subscriptions` — active subscription per tenant (plan, billing cycle, status, payment gateway, auto-renew)
2. `payments` — immutable payment ledger (amount, gateway, status, gateway tx id)
3. `billing_invoices` — generated invoices with auto-numbered invoice_number (INV-YYYYMMDD-NNNN)
4. `grace_period_config` — configurable grace days (global default=3, per-tenant override)
5. `subscription_events` — append-only lifecycle event log

## Security
- RLS enabled on all tables
- tenant_subscriptions/payments/invoices: tenant members can SELECT; super admin only INSERT/UPDATE
- grace_period_config: global row readable by all authenticated; super admin for CRUD
- subscription_events: tenant members SELECT; append-only (no UPDATE/DELETE)

## Notes
1. All enum types are created idempotently
2. Invoice numbers auto-generated by trigger (BEFORE INSERT)
3. Global grace period default (3 days) seeded on first run
4. updated_at maintained by trigger on all mutable tables
*/

