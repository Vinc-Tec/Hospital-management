-- 3. billing_invoices
CREATE TABLE IF NOT EXISTS billing_invoices (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invoice_number text UNIQUE NOT NULL DEFAULT '',
  tenant_id uuid NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
  subscription_id uuid REFERENCES tenant_subscriptions(id) ON DELETE SET NULL,
  amount_due numeric(12,2) NOT NULL CHECK (amount_due >= 0),
  amount_paid numeric(12,2) NOT NULL DEFAULT 0,
  due_date date NOT NULL,
  paid_at timestamptz,
  status invoice_status_enum NOT NULL DEFAULT 'draft',
  line_items jsonb NOT NULL DEFAULT '[]',
  pdf_url text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION fn_generate_invoice_number() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_date text := to_char(now(), 'YYYYMMDD');
  v_seq bigint;
BEGIN
  SELECT COALESCE(MAX((regexp_match(invoice_number, 'INV-' || v_date || '-(\d+)'))[1]::bigint), 0)
  INTO v_seq FROM billing_invoices WHERE invoice_number LIKE 'INV-' || v_date || '-%';
  NEW.invoice_number := 'INV-' || v_date || '-' || lpad((v_seq + 1)::text, 4, '0');
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS trg_inv_number ON billing_invoices;
CREATE TRIGGER trg_inv_number BEFORE INSERT ON billing_invoices FOR EACH ROW WHEN (NEW.invoice_number = '' OR NEW.invoice_number IS NULL) EXECUTE FUNCTION fn_generate_invoice_number();

