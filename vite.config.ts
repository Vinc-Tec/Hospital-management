import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

// https://vitejs.dev/config/
export default defineConfig({
  plugins: [react()],
  optimizeDeps: {
    exclude: ['lucide-react'],
  },
  build: {
    rollupOptions: {
      output: {
        // Vendor libraries change far less often than app code, so
        // splitting them into their own chunk lets browsers cache them
        // across deploys instead of re-downloading React itself every
        // time a single component changes. Purely a build/caching
        // change -- no runtime behavior is affected.
        manualChunks: {
          'react-vendor': ['react', 'react-dom', 'react-router-dom'],
          supabase: ['@supabase/supabase-js'],
        },
      },
    },
  },
});
